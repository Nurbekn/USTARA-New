import test from 'node:test';
import assert from 'node:assert/strict';
import { normalizeServiceName, parseServicePrice, stepServicePrice, validateServiceDraft } from '../src/pages/barber/data/serviceForm.js';
const valid = { name:'Soch olish',price:'45000',duration:30 };
const check=(changes)=>validateServiceDraft({...valid,...changes});
test('NFC Unicode normalization and whitespace collapsing',()=>assert.equal(normalizeServiceName('  Soch  o\u0308lish  '),'Soch ölish'));
test('normalization does not coerce arbitrary values',()=>assert.equal(normalizeServiceName(123),''));
test('normal service draft returns canonical fields',()=>assert.deepEqual(check({}),{ok:true,name:'Soch olish',price:45000,duration:30}));
test('Unicode names are allowed',()=>assert.equal(check({name:'Oʻgʻil bolalar'}).ok,true));
test('invisible characters are rejected',()=>assert.equal(check({name:'Soch\u200Bolish'}).ok,false));
test('control characters are rejected',()=>assert.equal(check({name:'Soch\u0001olish'}).ok,false));
test('short name is rejected',()=>assert.equal(check({name:'a'}).ok,false));
test('overlong name is rejected',()=>assert.equal(check({name:'a'.repeat(51)}).ok,false));
test('name 50 Unicode characters is accepted',()=>assert.equal(check({name:'a'.repeat(50)}).ok,true));
test('undefined draft is rejected safely',()=>assert.equal(validateServiceDraft(undefined).ok,false));
test('array draft is rejected safely',()=>assert.equal(validateServiceDraft([]).ok,false));
test('empty price is rejected',()=>assert.equal(check({price:''}).ok,false));
test('fractional price is rejected',()=>assert.equal(check({price:'1000.5'}).ok,false));
test('scientific notation price is rejected',()=>assert.equal(check({price:'1e6'}).ok,false));
test('negative price is rejected',()=>assert.equal(check({price:-1000}).ok,false));
test('too high price is rejected',()=>assert.equal(check({price:100000000}).ok,false));
test('price boundary values are accepted',()=>{assert.equal(parseServicePrice('1000'),1000);assert.equal(parseServicePrice(99999999),99999999)});
test('price stepper respects lower and upper limits',()=>{assert.equal(stepServicePrice('',-5000),1000);assert.equal(stepServicePrice(99999999,5000),99999999)});
test('duration must be in 5 minute increments',()=>{for(const duration of [0,6,25.5,65,'30']) assert.equal(check({duration}).ok,false)});
test('duration boundaries allowed',()=>{assert.equal(check({duration:5}).ok,true);assert.equal(check({duration:60}).ok,true)});

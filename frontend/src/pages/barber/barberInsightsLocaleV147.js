export function barberInsightsText(lang='uz') {
  const table = lang === 'ru' ? copies.ru : lang === 'en' ? copies.en : null;
  const previous = barberOpsText(lang);
  return (source,vars={}) => {
    if (typeof source !== 'string') return '';
    const value = table && Object.hasOwn(table,source) ? table[source] : previous(source);
    return value.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g,(match,key)=>
      vars && Object.hasOwn(vars,key) ? String(vars[key]) : match);
  };
}
export function hasBarberInsightsTranslation(lang,source) {
  const table = lang === 'ru' ? copies.ru : lang === 'en' ? copies.en : null;
  return !!table && typeof source === 'string' && Object.hasOwn(table,source);
}
export function barberInsightsDate(iso,lang='uz',today=new Date()) {
  // Pure display formatting; no mutation of server ISO dates or booking timestamps.
  if (typeof iso !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return iso;
  const date = new Date(`${iso}T12:00:00`);
  if (Number.isNaN(date.valueOf()) || date.getFullYear() !== Number(iso.slice(0,4)) ||
      date.getMonth()+1 !== Number(iso.slice(5,7)) || date.getDate() !== Number(iso.slice(8,10))) return iso;
  if (lang !== 'ru' && lang !== 'en') return null; // caller uses existing Uzbek dateLabel
  const start = new Date(today.getFullYear(),today.getMonth(),today.getDate());
  const diff = Math.round((new Date(date.getFullYear(),date.getMonth(),date.getDate())-start)/86400000);
  if (diff === 0) return lang === 'ru' ? 'Сегодня' : 'Today';
  if (diff === 1) return lang === 'ru' ? 'Завтра' : 'Tomorrow';
  if (diff === -1) return lang === 'ru' ? 'Вчера' : 'Yesterday';
  return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-US', {weekday:'long',day:'numeric',month:'long'}).format(date);
}

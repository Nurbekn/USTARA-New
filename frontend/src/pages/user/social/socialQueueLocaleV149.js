export function socialQueueText(lang = 'uz') {
  const table = lang === 'ru' ? RU : lang === 'en' ? EN : null;
  return source => typeof source === 'string'
    ? (table && Object.hasOwn(table, source) ? table[source] : source) : '';
}
export function hasSocialQueueTranslation(lang, key) {
  return typeof key === 'string' && (lang === 'ru' || lang === 'en')
    && Object.hasOwn(lang === 'ru' ? RU : EN, key);
}
// Let the existing validated model determine the numeric wait interval; localize its suffix only.
export function localizeQueueWait(formatted, lang = 'uz') {
  if (typeof formatted !== 'string' || !/^\d+–\d+ daqiqa \(taxminiy\)$/.test(formatted)) return null;
  if (lang === 'ru') return formatted.replace(/ daqiqa \(taxminiy\)$/, ' мин (примерно)');
  if (lang === 'en') return formatted.replace(/ daqiqa \(taxminiy\)$/, ' min (estimated)');
  return formatted;
}

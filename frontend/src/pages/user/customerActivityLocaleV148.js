export function customerActivityText(lang = 'uz') {
  const table = lang === 'ru' ? ru : lang === 'en' ? en : null;
  return (source) => {
    if (typeof source !== 'string') return '';
    return table && Object.hasOwn(table, source) ? table[source] : source;
  };
}
export function hasCustomerActivityTranslation(lang, source) {
  return (lang === 'ru' || lang === 'en') && typeof source === 'string'
    && Object.hasOwn(lang === 'ru' ? ru : en, source);
}
